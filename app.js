  function currentResetWeek(today) {
    const t = today ? new Date(today) : new Date(); t.setHours(0, 0, 0, 0);
    const start = RESET_DATES.start, end = RESET_DATES.end;
    if (t < start) return { state: "before", n: 0, daysToStart: Math.round((start - t) / 86400000) };
    if (t > end) return { state: "after", n: RESET_DATES.weeks };
    return { state: "active", n: Math.min(Math.floor((t - start) / 86400000 / 7) + 1, RESET_DATES.weeks) };
  }


  function bodyVerdict(sig) {
    if (!sig) return { label: "Отметь самочувствие", tone: "info", sub: "Отметь шкалы ниже — дам директиву на сегодня." };
    if (sig.swelling === "high" && sig.energy === "low") return { label: "Приоритет восстановлению", tone: "warn", sub: "Отёк + низкая энергия → вода, ходьба, дыхание. Без нагрузки." };
    if (sig.pelvic === "high") return { label: "Без нагрузки на таз", tone: "warn", sub: "Заменить бег и осевую нагрузку. Дыхание и релиз." };
    if (sig.swelling === "high") return { label: "Контроль отёка", tone: "warn", sub: "Вода, ходьба, меньше соли. Бег → ходьба." };
    if (sig.sleep === "poor" && sig.stress === "high") return { label: "Сначала нервная система", tone: "warn", sub: "Снизить RPE, осанка и дыхание. Без отказа." };
    if (sig.soreness === "high") return { label: "Снизить вес сегодня", tone: "info", sub: "Болезненность → меньше рабочий вес, без отказа." };
    if (sig.energy === "low") return { label: "Мобилизация + ходьба", tone: "info", sub: "Низкая энергия → лёгкое движение, короче сессия." };
    return { label: "Полноценная тренировка", tone: "ok", sub: "Сигналов к снижению нет — тренируйся по плану." };
  }

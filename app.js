  function epley1RM(w, reps) { const n = parseFloat(w) || 0, r = parseInt(reps) || 0; return n && r ? Math.round(n * (1 + r / 30)) : 0; }
  function suggestNext(exId, ready) {
    let hist = {}; try { hist = JSON.parse(localStorage.getItem("exerciseHistV1") || "{}") || {}; } catch {}
    const last = (hist[exId] && hist[exId].last) || null;
    const ex = EXERCISES[exId];
    if (ready && (ready.reduceLoad || ready.rpeCap === 6 || ready.phase === "break")) {
      return { action: "regress", note: last ? `Сегодня снизь вес (~−10%) от ${last.weight} кг — день восстановления.` : "Сегодня лёгкий вес, фокус на технике." };
    }
    if (!last) return { action: "start", note: `Начни с минимального веса. Цель: ${ex.rx.reps} повт., RPE ${ex.rx.rpe}.` };
    if (last.reps && parseInt(last.reps) >= parseInt(String(ex.rx.reps).split("–").pop()) && (last.rpe || 0) <= 7) {
      return { action: "increase", note: `В прошлый раз ${last.weight} кг × ${last.reps} при RPE ${last.rpe || "?"}. Добавь небольшой шаг веса.` };
    }
    return { action: "repeat", note: `Повтори ${last.weight} кг, добери повторения до верха диапазона при чистой технике.` };
  }


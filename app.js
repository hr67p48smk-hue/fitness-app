  function logSet(exId, weight, reps, rpe) {
    try {
      const hist = JSON.parse(localStorage.getItem("exerciseHistV1") || "{}") || {};
      const e = hist[exId] || { best: 0, bestReps: 0, e1rm: 0, entries: 0 };
      const w = parseFloat(weight) || 0, r = parseInt(reps) || 0, rm = epley1RM(w, r);
      e.last = { weight: w, reps: r, rpe: rpe || null, date: dayKey() };
      e.entries = (e.entries || 0) + 1;
      if (w > (e.best || 0)) e.best = w;
      if (rm > (e.e1rm || 0)) e.e1rm = rm;
      hist[exId] = e; localStorage.setItem("exerciseHistV1", JSON.stringify(hist));
    } catch {}
  }
  function finishSession(session) {
    try {
      const hist = JSON.parse(localStorage.getItem("trainHistV1") || "[]") || [];
      let totalSets = 0, volume = 0;
      Object.keys(session.log || {}).forEach((ex) => { (session.log[ex].sets || []).forEach((st) => { totalSets++; volume += (parseFloat(st.weight) || 0) * (parseInt(st.reps) || 0); }); });
      hist.unshift({ date: dayKey(), workout: session.name, sets: totalSets, volume: Math.round(volume), log: session.log });
      localStorage.setItem("trainHistV1", JSON.stringify(hist.slice(0, 200)));
    } catch {}
  }

